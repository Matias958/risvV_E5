def rows(art):
    w = len(art[0])
    assert all(len(r) == w for r in art), art
    return w, [int(r.replace(".", "0").replace("#", "1"), 2) for r in art]


print("/* Generado por gfx_gen.py: no editar a mano. */")
print("#ifndef GFX_H\n#define GFX_H\n#include <stdint.h>\n")
print("typedef struct { uint8_t w, h; const uint16_t *rows; } sprite_t;\n")
for name, art in SPRITES.items():
    w, r = rows(art)
    if w > 16:      # mapas de bits anchos (escudo): solo las filas, en 32 bits
        print(f"static const uint32_t {name}_rows[{len(r)}] = {{{', '.join(f'0x{v:06x}' for v in r)}}};")
        continue
    print(f"static const uint16_t {name}_rows[{len(r)}] = {{{', '.join(f'0x{v:04x}' for v in r)}}};")
    print(f"static const sprite_t {name} = {{{w}, {len(r)}, {name}_rows}};")
print("\n/* Fuente 5x7: font[c - ' '] para c en ' '..'Z' (7 filas, bit 4 = izquierda) */")
print("static const uint8_t font5x7[59][7] = {")
for c in range(32, 91):
    ch = chr(c)
    glyph = FONT.get(ch, FONT["?"] if ch not in FONT else FONT[ch])
    _, r = rows(glyph)
    print(f"    {{{', '.join(f'0x{v:02x}' for v in r)}}},  /* '{ch}' */")
print("};\n\n#endif")
